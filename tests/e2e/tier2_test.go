// F02: HMAC-SHA256 Signing & Anti-Replay Boundaries (5 subtests)
func TestTier2_F02_HMACSigningBoundaries(t *testing.T) {
	t.Run("F02_01_AutoGeneratedSecretWhenOmittedSignsValidHMAC", func(t *testing.T) {
		inst := startRelayHook(t)
		defer inst.Stop(t)
		srv := newWebhookCaptureServer(t, "")
		app := mustCreateApp(t, inst.BaseURL, "", "T2 F02 App 1")
		ep := mustCreateEndpoint(t, inst.BaseURL, app.ID, srv.URL, "", []string{"*"}, 3)
		if ep.Secret == "" {
			t.Fatal("expected non-empty auto-generated secret")
		}
		srv.SetSecret(ep.Secret)

		_ = mustIngestEvent(t, inst.BaseURL, app.ID, "auto.secret", map[string]any{"k": "v"}, "")
		reqs := srv.WaitForRequests(t, 1, 3*time.Second)
		if !reqs[0].HMACValid {
			t.Fatalf("expected valid HMAC using auto-generated secret %q: %s", ep.Secret, reqs[0].HMACError)
		}
	})

	t.Run("F02_02_ExpiredTimestampRejected", func(t *testing.T) {
		mock := startMockReceiver(t, "-secret", "whsec_t2_f02")
		payload := []byte(`{"msg":"old"}`)
		oldTS := time.Now().Add(-10 * time.Minute).Unix()
		sig := signPayloadStdlib("whsec_t2_f02", payload, oldTS)

		resp, _ := doJSONRequest(t, http.MethodPost, mock.WebhookURL, payload, map[string]string{
			"X-RelayHook-Signature": sig,
			"X-RelayHook-Timestamp": strconv.FormatInt(oldTS, 10),
		})
		if resp.StatusCode != http.StatusUnauthorized {
			t.Fatalf("expected 401 for expired timestamp, got %d", resp.StatusCode)
		}
	})

	t.Run("F02_03_FutureTimestampRejected", func(t *testing.T) {
		mock := startMockReceiver(t, "-secret", "whsec_t2_f02_fut")
		payload := []byte(`{"msg":"future"}`)
		futTS := time.Now().Add(10 * time.Minute).Unix()
		sig := signPayloadStdlib("whsec_t2_f02_fut", payload, futTS)

		resp, _ := doJSONRequest(t, http.MethodPost, mock.WebhookURL, payload, map[string]string{
			"X-RelayHook-Signature": sig,
			"X-RelayHook-Timestamp": strconv.FormatInt(futTS, 10),
		})
		if resp.StatusCode != http.StatusUnauthorized {
			t.Fatalf("expected 401 for future timestamp (>5m), got %d", resp.StatusCode)
		}
	})

	t.Run("F02_04_SingleBitFlippedHexDigestRejected", func(t *testing.T) {
		mock := startMockReceiver(t, "-secret", "whsec_t2_f02_flip")
		payload := []byte(`{"msg":"flip"}`)
		now := time.Now().Unix()
		sig := signPayloadStdlib("whsec_t2_f02_flip", payload, now)
		last := sig[len(sig)-1]
		rep := byte('a')
		if last == 'a' {
			rep = 'b'
		}
		flipped := sig[:len(sig)-1] + string(rep)

		resp, _ := doJSONRequest(t, http.MethodPost, mock.WebhookURL, payload, map[string]string{
			"X-RelayHook-Signature": flipped,
			"X-RelayHook-Timestamp": strconv.FormatInt(now, 10),
		})
		if resp.StatusCode != http.StatusUnauthorized {
			t.Fatalf("expected 401 for 1-nibble flipped signature, got %d", resp.StatusCode)
		}
	})

	t.Run("F02_05_MalformedSignatureHeadersRejected", func(t *testing.T) {
		mock := startMockReceiver(t, "-secret", "whsec_t2_f02_mal")
		payload := []byte(`{"msg":"malformed"}`)
		for _, hdr := range []string{"", "v1=deadbeef", "t=notanumber,v1=abcd", "t=1700000000,v1=zzzz"} {
			resp, _ := doJSONRequest(t, http.MethodPost, mock.WebhookURL, payload, map[string]string{
				"X-RelayHook-Signature": hdr,
			})
			if resp.StatusCode != http.StatusUnauthorized {
				t.Fatalf("expected 401 for malformed header %q, got %d", hdr, resp.StatusCode)
			}
		}
	})
}

